/** 鱼种图在 CDN 上的目录 */
export const FISH_IMAGE_DIR = `${ENV.cdnBaseUrl}/fish`;

/** 按鱼种 id 取图片地址。取不到返回空串，让调用方走占位 */
export function fishImageUrl(id: FishSpeciesId): string {
  const entry = FISH_IMAGES[id];
  return entry ? `${FISH_IMAGE_DIR}/${entry.file}` : '';
}

