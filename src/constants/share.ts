/**
 * 海报的版式尺寸。
 *
 * 位图 750×1000（3:4）。这个尺寸是**画布的坐标系**，不是屏幕尺寸：
 * canvas 2d 的绘制坐标与位图分辨率是同一套数，跟 dpr 无关。
 *
 * 750 的由来：375pt 机型 @2x。海报是要存进相册、被人转发出去的，
 * 按 750 画在 2x 屏上不虚，3x 屏上略软但仍然够用；
 * 画得再大（1080）只是让位图更大、导出更慢，收益不明显。
 */
export const POSTER = {
  /** 位图宽 */
  width: 750,
  /** 位图高 */
  height: 1000,

  /**
   * 微信转发封面的裁切带（5:4 = 600 高）。
   *
   * 这一刀裁的是**主票的上半张**：照片、名字、副信息、分数都在带子里，
   * 齿孔线（poster.ts 的 LAYOUT.ruleY = 775）在带子下面 ——
   * 卡的下沿是那道分界线，不是被切了一半的存根。
   *
   * 为什么不是居中裁（200–800）：居中裁的那一刀正好切在齿孔线下面几十像素，
   * 卡的下沿变成一条浮在空白里的发丝线，读起来像「被切了半张」。
   * 往上收到 100 之后，卡里是**一张完整的主票**：照片占上面三分之二，
   * 数字贴着下沿站住，一眼看得出是刻意裁的。
   *
   * ⚠️ 主票里的**地址不在带子里**（它的墨迹上沿在 715，在 700 之下）。
   * 带上它的话，那个尺寸下一行地址只剩几个像素高，糊成一团不如没有。
   */
  cardTop: 100,
  cardHeight: 600,
} as const;

/**
 * 海报导出成什么格式。
 *
 * 为什么是 PNG 不是 JPEG：海报右下角那块小程序码是**黑白高对比的小图案**，
 * JPEG 在这种地方最容易出振铃（ringing）—— 边缘一糊，码就扫不出来。
 * 而「码扫不出来」是这张海报最硬的失败：海报本身再好看，扫不出东西就没有意义。
 *
 * 体积换清晰度，这笔买卖不亏 —— 一张 750×1000 的 PNG 也就几百 KB。
 */
export const POSTER_EXPORT = {
  fileType: 'png',
} as const;
