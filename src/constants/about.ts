/**
 * 一行可点开的条目。
 *
 * 现在只有关于页的协议列表在用 —— 「我的」页的入口行改用了 MineRow：
 * 那一页的行要带行首图标、右侧数量与待审徽标，不再是「一行字 + 一个箭头」。
 */
export interface AboutLink {
  /** 行标题 */
  key: string;
}

/**
 * 一篇文档里的一章。
 *
 * 为什么分章：协议与隐私政策是**逐条读**的材料 —— 一段接一段地读下来，
 * 才知道每一条在讲什么边界。全塞成十几段不分章的散文，读到第三条就开始滑过去，
 * 读者找不到「哪一条跟我有关」。
 *
 * 条款标题（「一、总则」）是**法律文件的写法**，不是界面元素的写法 ——
 * 用户是来读一份有编号的文件的，编号让他能引用、能对照、能记住自己看过第几条。
 */
export interface AboutDocSection {
  /** 条款标题。带中文序号（「一、总则」），跟正文的编号对得上 */
  title: string;
  /** 条款正文。分段给是因为一条里有几件事要分开说 */
  paragraphs: readonly string[];
}

/** 一篇文档。抽屉里渲染的就是这个形状 */
export interface AboutDoc extends AboutLink {
  /**
   * 标记它是文档，不是外部入口。
   *
   * 页面靠它分派点开的行为 —— 协议区里还有一行是打开微信官方弹窗的，
   * 那一行没有正文（见 PrivacyContractEntry）。
   */
  readonly kind: 'doc';
  /** 抽屉副标题，一句话说明这篇讲什么 */
  summary: string;
  /** 一行元信息（生效日期等）。没有就不写这一行 */
  meta?: string;
  /** 章节 */
  sections: readonly AboutDocSection[];
}

/**
 * 微信官方隐私协议那一行。
 *
 * 点开不是抽屉，是微信后台那份「用户隐私保护指引」—— 平台要求用户能直达。
 */
export interface PrivacyContractEntry {
  readonly kind: 'privacy-contract';
  /** 行标题 */
  readonly key: string;
  /**
   * 官方那版打不开时退回的本地全文行标题。
   *
   * 官方协议能不能弹，取决于后台配没配「用户隐私保护指引」（没配直接 fail）。
   * 这时候让用户读到本地全文，好过按下去什么都没发生。
   */
  readonly fallbackKey: string;
}

